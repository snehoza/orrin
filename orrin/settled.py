"""Settled questions: what was tried, what happened, and why not to redo it.

Much of what keeps a long project from going in circles is a record of the ideas that were
already measured and rejected (or adopted), with the result. Agents read it before proposing
work; the check-in flags an open task that looks like a settled idea.

``<agents_dir>/settled.jsonl`` (append-only) renders to ``SETTLED.md``. ``reopen`` an item when
something has changed that makes it worth another look, and say what.
"""
from __future__ import annotations

import json
import re
import time

from .config import Config

STOP = {"the", "a", "an", "and", "or", "of", "to", "in", "on", "for", "with", "by", "is", "it", "as", "at",
        "be", "use", "using", "from", "into", "add", "make", "try", "new", "more", "less"}


def _path(cfg: Config):
    return cfg.agents_dir / "settled.jsonl"


def _words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if len(w) > 2 and w not in STOP}


def items(cfg: Config) -> dict[str, dict]:
    out: dict[str, dict] = {}
    p = _path(cfg)
    if not p.exists():
        return out
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        e = json.loads(line)
        if e["event"] == "add":
            out[e["id"]] = dict(e, status="settled")
        elif e["event"] == "reopen" and e["id"] in out:
            out[e["id"]].update(status="reopened", reopen_why=e["why"], reopened=e["date"])
    return out


def _append(cfg: Config, event: dict) -> None:
    p = _path(cfg)
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(event, ensure_ascii=False) + "\n")


def add(cfg: Config, idea: str, result: str, verdict: str = "rejected", evidence: str = "") -> dict:
    existing = items(cfg)
    n = 1 + max((int(k[1:]) for k in existing if k[1:].isdigit()), default=0)
    e = {"event": "add", "id": f"S{n}", "idea": idea.strip(), "result": result.strip(), "verdict": verdict,
         "evidence": evidence, "date": time.strftime("%Y-%m-%d")}
    _append(cfg, e)
    render(cfg)
    return e


def reopen(cfg: Config, sid: str, why: str) -> dict:
    if sid not in items(cfg):
        raise ValueError(f"no settled item {sid}")
    e = {"event": "reopen", "id": sid, "why": why.strip(), "date": time.strftime("%Y-%m-%d")}
    _append(cfg, e)
    render(cfg)
    return e


def matches(cfg: Config, text: str, threshold: float = 0.5) -> list[dict]:
    """Settled items whose idea shares most of its key words with ``text``."""
    words = _words(text)
    out = []
    for it in items(cfg).values():
        if it["status"] != "settled":
            continue
        idea = _words(it["idea"])
        if not idea or not words:
            continue
        score = len(idea & words) / min(len(idea), len(words))
        if score >= threshold:
            out.append(dict(it, score=round(score, 2)))
    return sorted(out, key=lambda x: -x["score"])


def render(cfg: Config):
    rows = sorted(items(cfg).values(), key=lambda x: x["date"], reverse=True)
    lines = ["# Settled", "", "<!-- Generated by `orrin settled`. -->", "",
             "Ideas already measured. Read this before proposing work; don't retry a settled idea unchanged. "
             "If something changed that makes one worth another look, `orrin settled reopen` it and say what.", ""]
    for it in rows:
        tag = it["verdict"] if it["status"] == "settled" else f"reopened {it['reopened']}: {it['reopen_why']}"
        ev = f" Evidence: {it['evidence']}." if it.get("evidence") else ""
        lines.append(f"- **{it['id']}** [{tag}] {it['idea']} -> {it['result']} ({it['date']}).{ev}")
    if not rows:
        lines.append("- Nothing yet.")
    target = cfg.agents_dir / "SETTLED.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return target
