"""Rules that evolve: a dated log of the user's corrections, rendered into the agent rules file.

A workflow that works is not a fixed rule set. It is what is left after many corrections: the
user says "don't do that" or "do it this way", and the rule changes the same day. So rules are
cheap to change here:

* ``add`` records a rule with the user's own words and the date, optionally superseding older rules;
* ``retire`` drops a rule that no longer serves the work, with the reason;
* ``render`` writes the live rules (plus the decision boundary and model policy from
  ``coordinator.json``) between markers in ``AGENT_RULES.md``, and the retired ones into
  ``RULES_HISTORY.md``, so agents read short current rules while the history stays auditable.

Storage: ``<agents_dir>/rules.jsonl``, one JSON object per event, append-only.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

from .config import Config

BEGIN, END = "<!-- coordinator:rules -->", "<!-- /coordinator:rules -->"


def log_path(cfg: Config) -> Path:
    return cfg.agents_dir / "rules.jsonl"


def events(cfg: Config) -> list[dict]:
    path = log_path(cfg)
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def state(cfg: Config) -> dict[str, dict]:
    """Replay the log: rule id -> rule with its status (live / superseded / retired)."""
    rules: dict[str, dict] = {}
    for e in events(cfg):
        if e["event"] == "add":
            rules[e["id"]] = dict(e, status="live")
            for old in e.get("supersedes", []):
                if old in rules and rules[old]["status"] == "live":
                    rules[old].update(status="superseded", superseded_by=e["id"], ended=e["date"])
        elif e["event"] == "retire" and e["id"] in rules:
            rules[e["id"]].update(status="retired", ended=e["date"], retire_why=e.get("why", ""))
    return rules


def _append(cfg: Config, event: dict) -> None:
    path = log_path(cfg)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(event, ensure_ascii=False) + "\n")


def add(cfg: Config, text: str, why: str = "", by: str = "user", section: str = "General",
        supersedes: list[str] | None = None, date: str | None = None) -> dict:
    rules = state(cfg)
    for old in supersedes or []:
        if old not in rules:
            raise ValueError(f"no rule {old}")
    number = 1 + max((int(r[1:]) for r in rules if r[1:].isdigit()), default=0)
    event = {"event": "add", "id": f"R{number}", "text": text.strip(), "why": why.strip(), "by": by,
             "section": section, "supersedes": list(supersedes or []), "date": date or time.strftime("%Y-%m-%d")}
    _append(cfg, event)
    return event


def retire(cfg: Config, rule_id: str, why: str, date: str | None = None) -> dict:
    rules = state(cfg)
    if rule_id not in rules or rules[rule_id]["status"] != "live":
        raise ValueError(f"no live rule {rule_id}")
    event = {"event": "retire", "id": rule_id, "why": why.strip(), "date": date or time.strftime("%Y-%m-%d")}
    _append(cfg, event)
    return event


def _origin(r: dict) -> str:
    who = f"{r['by']} {r['date']}"
    return f"{who}: \"{r['why']}\"" if r.get("why") else who


def render_block(cfg: Config) -> str:
    rules = [r for r in state(cfg).values() if r["status"] == "live"]
    b, m = cfg["boundary"], cfg["models"]
    out = [BEGIN, "<!-- Generated by `coordinator rule render` from rules.jsonl and coordinator.json. "
                  "Change rules with `coordinator rule add/retire`, not by editing this block. -->", "",
           "## Decision boundary", "Decide and act, then report:"]
    out += [f"- {x}" for x in b["decide"]]
    out += ["", "Stop and ask the user first:"] + [f"- {x}" for x in b["ask"]]
    out += ["", "## Models and budget"]
    out += [f"- {role}: {who}" for role, who in m["roles"].items()]
    if m.get("fallback"):
        out.append("- When a model or account is out of quota, fall back in this order: " + " -> ".join(m["fallback"]) + ".")
    if m.get("checkpoint_usage_percent"):
        out.append(f"- At {m['checkpoint_usage_percent']}% of a usage window, checkpoint the agents on it "
                   "(commit, update the handoff) before they are cut off.")
    if m.get("relaunch_context_tokens"):
        out.append(f"- Relaunch an agent fresh from its handoff at about {m['relaunch_context_tokens']:,} tokens of context, "
                   "or earlier if it starts re-reading or forgetting its brief.")
    sections: dict[str, list[dict]] = {}
    for r in rules:
        sections.setdefault(r["section"], []).append(r)
    for name, items in sections.items():
        out += ["", f"## {name}"]
        out += [f"- {r['text']} ({r['id']}; {_origin(r)})" for r in items]
    if not rules:
        out += ["", "## Rules", "- None yet. They are added as the user corrects the work."]
    out.append(END)
    return "\n".join(out)


def render(cfg: Config) -> tuple[Path, Path]:
    target = cfg.agents_dir / "AGENT_RULES.md"
    text = target.read_text(encoding="utf-8") if target.exists() else f"# Agent rules\n\n{BEGIN}\n{END}\n"
    if BEGIN not in text or END not in text:
        text = text.rstrip("\n") + f"\n\n{BEGIN}\n{END}\n"
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(head + render_block(cfg) + tail, encoding="utf-8", newline="\n")
    history = cfg.agents_dir / "RULES_HISTORY.md"
    old = [r for r in state(cfg).values() if r["status"] != "live"]
    lines = ["# Rules history", "", "Rules that were superseded or retired, newest first. Live rules are in AGENT_RULES.md.", ""]
    for r in sorted(old, key=lambda r: r["ended"], reverse=True):
        end = f"superseded by {r['superseded_by']}" if r["status"] == "superseded" else f"retired: {r.get('retire_why', '')}"
        lines.append(f"- **{r['id']}** ({r['date']} -> {r['ended']}, {end}): {r['text']} ({_origin(r)})")
    if not old:
        lines.append("- Nothing yet.")
    history.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return target, history
